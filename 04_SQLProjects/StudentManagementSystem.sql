-- 1. What is a Primary Key? 
-- ==================================================================================================== 

	A Primary Key is a column (or set of columns) that uniquely identifies each record in a 
	table. It cannot contain NULL or duplicate values. 
    
-- ==================================================================================================== 
-- 2. Difference between WHERE and HAVING. 
-- ==================================================================================================== 
-- WHERE
-- ==================================================================================================== 
	
    Filters rows before grouping. 
	Used with SELECT, UPDATE, DELETE. 
    Cannot use aggregate functions directly. 
    
-- ==================================================================================================== 
-- HAVING 
-- ==================================================================================================== 

	Filters groups after GROUP BY. 
	Mostly used with GROUP BY. 
	Can use aggregate functions like COUNT(), SUM(), AVG(). 
    
-- ==================================================================================================== 
-- 3. Difference between DELETE, DROP and TRUNCATE. 
-- ==================================================================================================== 
-- DELETE 
-- ==================================================================================================== 

	Deletes specific rows or all rows.
	WHERE clause can be used.
	Table structure remains.
    
-- ====================================================================================================  
-- TRUNCATE 
-- ==================================================================================================== 

	Removes all rows from a table.
	Cannot use WHERE.
	Table structure remains.
	Faster than DELETE. 
    
-- ==================================================================================================== 
-- DROP 
-- ==================================================================================================== 
	
    Deletes the entire table, including:

			Data
			Structure
			Constraints
			Indexes 
            
-- ==================================================================================================== 
-- 4. Difference between CHAR and VARCHAR. 
-- ==================================================================================================== 
-- CHAR 
-- ==================================================================================================== 

	Fixed-length data type.
	Faster for fixed-size data.
	Example: CHAR(10)
    
-- ==================================================================================================== 
-- VARCHAR 
-- ==================================================================================================== 

	Variable-length data type. 
	Saves storage space. 
	Example: VARCHAR(10) 
    
-- ==================================================================================================== 
-- 5. What is GROUP BY? 
-- ==================================================================================================== 

	GROUP BY is used to group rows having the same values in one or more columns, usually 
	with aggregate functions like COUNT(), SUM(), AVG(), MAX(), and MIN().
    
-- ==================================================================================================== 
-- 6. What is ORDER BY? 
-- ==================================================================================================== 

 ORDER BY is used to sort records in ascending (ASC) or descending (DESC) order. 
 
-- ==================================================================================================== 
-- 7. Difference between COUNT() and SUM(). 
-- ==================================================================================================== 
-- COUNT() 
-- ==================================================================================================== 

	Counts the number of rows.
	Works on any column.  
    
-- ==================================================================================================== 
-- SUM() 
-- ==================================================================================================== 

	Adds numeric values. 
	Works only on numeric columns. 
    
-- ==================================================================================================== 
-- 8. What is the purpose of LIMIT? 
-- ==================================================================================================== 
	LIMIT is used to restrict the number of rows returned by a query 
